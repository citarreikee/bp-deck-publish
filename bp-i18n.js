  function normalize(text) {
    return text.replace(/\s+/g, ' ').trim();
  }

  function collectTextNodes() {
    const nodes = [];
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
        const parent = node.parentElement;
        if (!parent || parent.closest('script,style')) return NodeFilter.FILTER_REJECT;
        return BP_I18N[normalize(node.nodeValue)] ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
      }
    });
    while (walker.nextNode()) {
      const node = walker.currentNode;
      const original = node.nodeValue;
      nodes.push({
        node,
        zh: original,
        en: original.replace(original.trim(), BP_I18N[normalize(original)])
      });
    }
    return nodes;
  }

  function addButton(applyLanguage) {
    if (document.querySelector('.lang-toggle')) return;
    const button = document.createElement('button');
    button.type = 'button';
    button.className = 'lang-toggle';
    button.setAttribute('aria-label', 'Switch language');
    button.innerHTML = '<span class="en-label">EN</span><span class="zh-label">中文</span>';
    button.addEventListener('click', () => {
      applyLanguage(document.body.classList.contains('lang-en') ? 'zh' : 'en');
    });
    document.body.appendChild(button);
  }

  function init() {
    const textNodes = collectTextNodes();
    const applyLanguage = (lang) => {
      const useEnglish = lang === 'en';
      document.documentElement.lang = useEnglish ? 'en' : 'zh-CN';
      document.body.classList.toggle('lang-en', useEnglish);
      for (const item of textNodes) {
        item.node.nodeValue = useEnglish ? item.en : item.zh;
      }
      document.title = useEnglish ? BP_I18N['熵增力场bp'] : '熵增力场bp';
      localStorage.setItem('bp-lang', useEnglish ? 'en' : 'zh');
      const url = new URL(location.href);
      if (useEnglish) url.searchParams.set('lang', 'en');
      else url.searchParams.delete('lang');
      history.replaceState(null, '', url);
    };

    addButton(applyLanguage);
    const initial = new URLSearchParams(location.search).get('lang') || localStorage.getItem('bp-lang') || 'zh';
    applyLanguage(initial === 'en' ? 'en' : 'zh');
    window.__bpSetLanguage = applyLanguage;
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init, { once: true });
  } else {
    init();
  }
